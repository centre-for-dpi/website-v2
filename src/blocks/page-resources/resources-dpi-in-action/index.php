<script>
  (function () {
    function initResDpiSlider() {
      if (typeof jQuery === 'undefined' || typeof jQuery.fn.slick === 'undefined') return;

      var $slider = jQuery('.res-dpi-action__slider');

      if ($slider.hasClass('slick-initialized')) return;

      $slider.slick({
        infinite: true,
        autoplay: true,
        autoplaySpeed: 4000,
        pauseOnHover: true,
        arrows: false,
        dots: false,
        slidesToShow: 3,
        slidesToScroll: 1,
        responsive: [
          {
            breakpoint: 991,
            settings: {
              slidesToShow: 2,
              slidesToScroll: 1,
            },
          },
          {
            breakpoint: 575,
            settings: {
              slidesToShow: 1,
              slidesToScroll: 1,
            },
          },
        ],
      });

      jQuery('.res-dpi-action__arrow--prev').on('click', function () {
        $slider.slick('slickPrev');
      });

      jQuery('.res-dpi-action__arrow--next').on('click', function () {
        $slider.slick('slickNext');
      });
    }

    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', initResDpiSlider);
    } else {
      initResDpiSlider();
    }
  })();
</script>
