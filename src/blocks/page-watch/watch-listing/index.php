<script>
document.addEventListener('DOMContentLoaded', function() {
  const modal = document.getElementById('videoModal');
  const modalTitle = document.getElementById('videoModalTitle');
  const modalIframe = document.getElementById('videoModalIframe');
  const closeBtn = document.getElementById('videoModalClose');
  const backBtn = document.getElementById('videoModalBack');
  const playButtons = document.querySelectorAll('.video-card__play');

  // Open modal
  playButtons.forEach(function(btn) {
    btn.addEventListener('click', function() {
      const title = this.getAttribute('data-video-title');
      const url = this.getAttribute('data-video-url');
      
      modalTitle.textContent = title;
      modalIframe.src = url + '?autoplay=1';
      modal.classList.add('active');
      document.body.style.overflow = 'hidden';
    });
  });

  // Close modal function
  function closeModal() {
    modal.classList.remove('active');
    modalIframe.src = '';
    document.body.style.overflow = '';
  }

  // Close button
  closeBtn.addEventListener('click', closeModal);
  backBtn.addEventListener('click', closeModal);

  // Close on backdrop click
  modal.addEventListener('click', function(e) {
    if (e.target === modal) {
      closeModal();
    }
  });

  // Close on escape key
  document.addEventListener('keydown', function(e) {
    if (e.key === 'Escape' && modal.classList.contains('active')) {
      closeModal();
    }
  });
});
</script>
